#!/usr/bin/env python3
"""校验角色卡、playbook 与全仓禁词。有任何问题则以非零状态退出。"""
import os
import re
import sys
from pathlib import Path

REQUIRED_KEYS = ["name", "title", "dept", "description", "cadence", "inputs", "outputs", "handoff"]
SECTIONS = ["使命", "什么时候派", "开工先读", "工作步骤", "必查清单", "不做的事", "交付", "交接给谁"]
PLAYBOOK_SECTIONS = ["触发条件", "岗位与顺序", "可并行", "交接物", "收尾标准"]
MIN_LINES, MAX_LINES = 60, 150
EXPECT_ROLES, EXPECT_PLAYBOOKS = 33, 6

FORBIDDEN = ["Generated by", "AI生成", "TBD", "草稿", "待确认"]
# 各自项目的私有词（项目名、域名、账号等）写在仓库根的 .denylist.local，每行一个；该文件不进仓库。
LOCAL_DENYLIST = ".denylist.local"
SKIP_DIRS = {".git", ".work", "dist", "__pycache__"}
SKIP_ROOT_FILES = {LOCAL_DENYLIST}
# 校验脚本与测试本身要列出禁词，不参与扫描；LICENSE 允许出现版权人名。
SCAN_SKIP_FILES = {"scripts/check.py", "tests/test_build.py"}
LICENSE_ALLOWED = {"fandral"}
TEXT_SUFFIXES = {".md", ".py", ".txt", ".json", ".yml", ".yaml", ""}


def parse_card(text):
    """返回 (frontmatter dict, body str)；格式不对返回 (None, text)。"""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            meta = {}
            for ln in lines[1:i]:
                if not ln.strip():
                    continue
                if ":" not in ln:
                    return None, text
                k, v = ln.split(":", 1)
                meta[k.strip()] = v.strip()
            return meta, "\n".join(lines[i + 1:]).lstrip("\n")
    return None, text


def role_files(root):
    base = Path(root) / "roles"
    if not base.is_dir():
        return []
    return sorted(p for p in base.glob("*/*.md") if not p.name.startswith("_"))


def iter_text_files(root):
    root = Path(root)
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for fn in sorted(filenames):
            p = Path(dirpath) / fn
            if p.suffix in TEXT_SUFFIXES:
                yield p


def check(root, expect_roles=None, expect_playbooks=None):
    root = Path(root)
    errors = []
    names = {}
    cards = []
    for p in role_files(root):
        rel = p.relative_to(root).as_posix()
        text = p.read_text(encoding="utf-8")
        meta, body = parse_card(text)
        if meta is None:
            errors.append(f"{rel}: frontmatter 缺失或格式错误")
            continue
        for k in REQUIRED_KEYS:
            if not meta.get(k):
                errors.append(f"{rel}: 缺少字段 {k}")
        name = meta.get("name", "")
        if name:
            if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
                errors.append(f"{rel}: name 须为小写连字符 ({name})")
            if name in names:
                errors.append(f"{rel}: name 重复 ({name}，另见 {names[name]})")
            names[name] = rel
            if p.stem != name:
                errors.append(f"{rel}: 文件名须与 name 一致")
        if meta.get("dept") and meta["dept"] != p.parent.name:
            errors.append(f"{rel}: dept 须与所在目录一致")
        heads = re.findall(r"^## (.+?)\s*$", body, flags=re.M)
        for s in SECTIONS:
            if s not in heads:
                errors.append(f"{rel}: 缺少章节 ## {s}")
        present = [h for h in heads if h in SECTIONS]
        if present != [s for s in SECTIONS if s in present]:
            errors.append(f"{rel}: 章节顺序与规定不一致")
        n = len(text.rstrip("\n").split("\n"))
        if not MIN_LINES <= n <= MAX_LINES:
            errors.append(f"{rel}: 行数 {n} 不在 {MIN_LINES}-{MAX_LINES}")
        cards.append((rel, meta, text))

    for rel, meta, _ in cards:
        for h in [x.strip() for x in meta.get("handoff", "").split(",") if x.strip()]:
            if h not in names:
                errors.append(f"{rel}: handoff 指向不存在的角色 {h}")

    pbs = sorted((root / "playbooks").glob("*.md")) if (root / "playbooks").is_dir() else []
    for p in pbs:
        rel = p.relative_to(root).as_posix()
        text = p.read_text(encoding="utf-8")
        heads = re.findall(r"^## (.+?)\s*$", text, flags=re.M)
        for s in PLAYBOOK_SECTIONS:
            if s not in heads:
                errors.append(f"{rel}: 缺少章节 ## {s}")
        for ref in re.findall(r"`([a-z][a-z0-9]*(?:-[a-z0-9]+)+)`", text):
            if ref not in names:
                errors.append(f"{rel}: 引用了不存在的角色 {ref}")

    # 链接与路径引用
    link_re = re.compile(r"\]\(([^)\s]+)\)")
    path_re = re.compile(r"`((?:templates|playbooks|roles|scripts)/[A-Za-z0-9_./-]+\.(?:md|py))`")
    for p in iter_text_files(root):
        if p.suffix != ".md":
            continue
        rel = p.relative_to(root).as_posix()
        text = p.read_text(encoding="utf-8")
        for target in link_re.findall(text):
            if re.match(r"[a-z]+://|mailto:|#", target):
                continue
            t = target.split("#")[0]
            if t and not (p.parent / t).exists():
                errors.append(f"{rel}: 链接目标不存在 {target}")
        for target in path_re.findall(text):
            if not (root / target).exists():
                errors.append(f"{rel}: 引用的文件不存在 {target}")

    # 禁词
    forbidden = list(FORBIDDEN)
    local = root / LOCAL_DENYLIST
    if local.is_file():
        forbidden += [w.strip() for w in local.read_text(encoding="utf-8").splitlines()
                      if w.strip() and not w.startswith("#")]
    for p in iter_text_files(root):
        rel = p.relative_to(root).as_posix()
        if rel in SCAN_SKIP_FILES or rel in SKIP_ROOT_FILES:
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        for w in forbidden:
            if w in text:
                if rel == "LICENSE" and w in LICENSE_ALLOWED:
                    continue
                errors.append(f"{rel}: 含禁词 {w}")
        if rel not in {"LICENSE"} and re.search(r"[\w.+-]+@[\w-]+\.[\w.]+", text):
            errors.append(f"{rel}: 含邮箱")

    if expect_roles is not None and len(cards) != expect_roles:
        errors.append(f"角色数 {len(cards)}，应为 {expect_roles}")
    if expect_playbooks is not None and len(pbs) != expect_playbooks:
        errors.append(f"playbook 数 {len(pbs)}，应为 {expect_playbooks}")
    return errors, len(cards), len(pbs)


def main():
    root = Path(__file__).resolve().parent.parent
    errors, nr, npb = check(root, EXPECT_ROLES, EXPECT_PLAYBOOKS)
    print(f"角色数={nr} playbook数={npb}")
    if errors:
        for e in errors:
            print("错误:", e)
        print(f"共 {len(errors)} 项问题")
        return 1
    print("校验通过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
